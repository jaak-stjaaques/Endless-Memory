# Endless Memory: the constant tables of the engine (no float on the chip, so they are computed here).
#   python3 tools/gen_tables.py > firmware/src/em_tables.h
import math

FS = 44100.0
TICK = FS / 32.0            # control rate: every 32 frames


def arr(name, ctype, vals, per=12):
    out = [f"static const {ctype} {name}[{len(vals)}] = {{"]
    for i in range(0, len(vals), per):
        out.append("    " + ", ".join(str(v) for v in vals[i:i + per]) + ",")
    out.append("};")
    return "\n".join(out)


parts = ["/* generated by tools/gen_tables.py: do not edit */", "#pragma once", "#include <stdint.h>", ""]

# a sine, 1024 points, full scale
parts.append(arr("SINE", "int16_t", [round(32767 * math.sin(2 * math.pi * i / 1024)) for i in range(1024)], 16))

# phase increments for MIDI 120 .. 132 in 1/64 semitone steps (lower octaves: shift right)
inc = []
for i in range(768):
    f = 440.0 * 2 ** ((120 + i / 64.0 - 69) / 12.0)
    inc.append(f"{round(f * 2 ** 32 / FS)}u")
parts.append(arr("INC_TOP", "uint32_t", inc, 8))

# a raised cosine bell, 1 at 0, 0 at 256 (Q15)
parts.append(arr("BELL", "int16_t", [round(32767 * 0.5 * (1 + math.cos(math.pi * i / 256))) for i in range(257)], 16))

# envelope times: knob 0..100 -> 1 ms .. 10 s
ms = [1.0 * (10000.0 ** (k / 100.0)) for k in range(101)]
parts.append(arr("ENV_MS", "uint16_t", [min(65535, round(t)) for t in ms], 12))
# attack: linear, (1 << 24) / ticks
parts.append(arr("ATT_INC", "uint32_t", [f"{max(1, round((1 << 24) / (t * TICK / 1000.0)))}u" for t in ms], 8))
# decay / release: exponential, 3 time constants in the time (Q16 coefficient per tick)
coef = []
for t in ms:
    tau = max(0.3, t * TICK / 1000.0 / 3.0)
    coef.append(max(1, min(65535, round(65536 * (1 - math.exp(-1.0 / tau))))))
parts.append(arr("EXP_COEF", "uint16_t", coef, 12))

# LFO rates: knob 0..100 -> 0.05 .. 20 Hz, phase increment per tick
hz = [0.05 * (400.0 ** (k / 100.0)) for k in range(101)]
parts.append(arr("LFO_INC", "uint32_t", [f"{round(h * 2 ** 32 / TICK)}u" for h in hz], 8))
parts.append(arr("LFO_CHZ", "uint16_t", [round(h * 100) for h in hz], 12))   # centi-Hz, for the screen

# tone (low-pass): knob 0..100 -> 150 Hz .. 18 kHz, one-pole coefficient Q16
fc = [150.0 * (120.0 ** (k / 100.0)) for k in range(101)]
parts.append(arr("LP_COEF", "uint16_t", [min(65535, round(65536 * (1 - math.exp(-2 * math.pi * f / FS)))) for f in fc], 12))

# the 2-pole filters before echo and space (HP FREQ, LP FREQ): knob 0..100 -> 20 Hz .. 18 kHz,
# g = tan(pi fc / fs) in Q24 for the zero-delay state-variable filter, and the frequency for the screen
cut = [20.0 * (900.0 ** (k / 100.0)) for k in range(101)]
parts.append(arr("SVF_G", "int32_t", [round(math.tan(math.pi * f / FS) * (1 << 24)) for f in cut], 8))
parts.append(arr("CUT_HZ", "uint16_t", [round(f) for f in cut], 12))

print("\n\n".join(parts))
