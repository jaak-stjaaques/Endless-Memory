"""Make firmware/gen/felucca_font.h from IBM Plex Mono (SIL Open Font License 1.1, assets/fonts/).

Two sizes, both monospaced like the panel layout expects:
  FONT_S  16 px rows, 8 px advance, ASCII 32..126
  FONT_L  32 px rows, 16 px advance, ASCII 32..95 (capitals, lower case folds to upper)
Glyphs are rendered with FreeType's hinting (stems snap to whole pixels), then given a little
contrast so thin strokes stay solid on the small screen, and stored as 4-bit alpha.
  python3 tools/gen_font.py [--preview out.png]     needs: pip install freetype-py Pillow
"""
import sys
from pathlib import Path
import freetype

ROOT = Path(__file__).resolve().parent.parent
FONTS = ROOT / "assets" / "fonts"

# name, ttf, rows, advance, pad, baseline row, pixel size, first, last, contrast (lo, hi)
CUTS = [
    ("S", "IBMPlexMono-Medium.ttf", 16, 8, 2, 12, 13.6, 32, 126, (0.18, 0.80)),
    ("L", "IBMPlexMono-Medium.ttf", 32, 16, 4, 25, 27.0, 32, 95, (0.15, 0.85)),
]


def render(cut):
    name, ttf, rows, adv, pad, base, px, first, last, (lo, hi) = cut
    face = freetype.Face(str(FONTS / ttf))
    face.set_char_size(int(px * 64), 0, 72, 72)
    bw = adv + 2 * pad
    glyphs = []
    for ch in range(first, last + 1):
        face.load_char(chr(ch), freetype.FT_LOAD_RENDER | freetype.FT_LOAD_TARGET_NORMAL)
        g = face.glyph
        bm = g.bitmap
        cell = [[0] * bw for _ in range(rows)]
        # centre the ink on the advance (monospace: the font's own advance is a fraction off ours)
        fadv = g.advance.x / 64.0
        ox = pad + g.bitmap_left + int(round((adv - fadv) / 2.0))
        oy = base - g.bitmap_top
        for y in range(bm.rows):
            for x in range(bm.width):
                v = bm.buffer[y * bm.pitch + x] / 255.0
                cx, cy = ox + x, oy + y
                if 0 <= cx < bw and 0 <= cy < rows and v > 0:
                    v = min(1.0, max(0.0, (v - lo) / (hi - lo)))
                    cell[cy][cx] = max(cell[cy][cx], int(round(v * 15)))
        glyphs.append(cell)
    return glyphs, bw


def c_array(name, glyphs, bw, rows):
    bpr = (bw + 1) // 2
    data, off = [], []
    for cell in glyphs:
        off.append(len(data))
        for row in cell:
            r = row + [0]
            for i in range(0, bw, 2):
                data.append(r[i] << 4 | r[i + 1])
    return data, off


def main():
    out = ["/* generated by tools/gen_font.py from IBM Plex Mono Medium (assets/fonts, SIL OFL 1.1) */",
           "#pragma once", "#include <stdint.h>", "#define FONT_PAD 2  /* x scale for L, see below */", ""]
    preview = {}
    for cut in CUTS:
        name, ttf, rows, adv, pad, base, px, first, last, _ = cut
        glyphs, bw = render(cut)
        preview[name] = (glyphs, bw, rows, adv, pad, first)
        data, off = c_array(name, glyphs, bw, rows)
        n = len(glyphs)
        out.append(f"static const uint8_t FONT_{name}_DATA[{len(data)}] = {{")
        for i in range(0, len(data), 24):
            out.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 24]) + ",")
        out.append("};")
        out.append(f"static const uint16_t FONT_{name}_OFF[{n}] = {{{', '.join(map(str, off))}}};")
        out.append(f"static const uint8_t FONT_{name}_ADV[{n}] = {{{', '.join([str(adv)] * n)}}};")
        out.append(f"static const uint8_t FONT_{name}_BW[{n}] = {{{', '.join([str(bw)] * n)}}};")
        out.append(f"static const felucca_font_t FONT_{name} = {{ {rows}, {pad}, {first}, {last}, FONT_{name}_ADV, "
                   f"FONT_{name}_BW, FONT_{name}_OFF, FONT_{name}_DATA }};")
        out.append("")
    (ROOT / "firmware" / "gen" / "felucca_font.h").write_text("\n".join(out))
    if len(sys.argv) > 2 and sys.argv[1] == "--preview":
        from PIL import Image
        lines = [("S", "ENDLESS MEMORY  0.3  dev"), ("S", "1 CLIMB  +18   2 BRIGHT 0"), ("S", "VOLUME ENVELOPE 251 MS"),
                 ("S", "abcdefghijklm nopqrstuvwxyz"), ("S", "0123456789 #%+-./:<>?[]"), ("L", "F#4 OFF 120"), ("L", "ENDLESS")]
        H = sum(preview[k][2] + 4 for k, _ in lines)
        im = Image.new("RGB", (240, H), (0, 0, 0))
        y = 0
        for k, s in lines:
            glyphs, bw, rows, adv, pad, first = preview[k]
            x = 4
            for ch in s:
                c = ord(ch.upper()) if k == "L" and "a" <= ch <= "z" else ord(ch)
                cell = glyphs[c - first]
                for yy in range(rows):
                    for xx in range(bw):
                        v = cell[yy][xx]
                        if v:
                            px_ = x - pad + xx
                            if 0 <= px_ < 240:
                                a = v / 15
                                o = im.getpixel((px_, y + yy))
                                im.putpixel((px_, y + yy), tuple(max(o[i], int(232 * a)) for i in range(3)))
                x += adv
            y += rows + 4
        im.resize((240 * 4, H * 4), Image.NEAREST).save(sys.argv[2])


if __name__ == "__main__":
    main()
